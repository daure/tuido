#[cfg(test)]
mod tests {
    use super::ACTION_VERBS;

    #[test]
    fn vocabulary_is_sorted_unique_lowercase_ascii_and_substantial() {
        assert!(ACTION_VERBS.len() >= 450);
        assert!(ACTION_VERBS.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(ACTION_VERBS.iter().all(|verb| {
            !verb.is_empty()
                && verb.is_ascii()
                && verb.bytes().all(|byte| byte.is_ascii_lowercase())
        }));
    }
}
